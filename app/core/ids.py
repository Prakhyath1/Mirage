"""Identifier generation and validation for MIRAGE runtime objects.

All IDs are generated by the server, never taken from untrusted input.
"""
from __future__ import annotations

import re
import secrets

# IDs are prefixed by object kind and carry 32 lowercase alphanumeric
# entropy characters (192 bits of randomness at generation time).
# ``is_valid_id`` accepts the same shape, so every server-generated ID
# passes the boundary check while attacker-supplied junk never does.
_ID_RE = re.compile(r"^[a-z]+_[a-z0-9]{26,32}$")


def _entropy() -> str:
    """32 url-safe, lowercase, alphanumeric characters."""
    return (
        secrets.token_urlsafe(24).replace("-", "a").replace("_", "b").lower()
    )


def new_session_id() -> str:
    """Generate an unguessable session identifier (server-side only)."""
    return f"sess_{_entropy()}"


def new_command_id() -> str:
    """Generate an unguessable command identifier (server-side only)."""
    return f"cmd_{_entropy()}"


def new_event_id() -> str:
    """Generate an unguessable event identifier (server-side only)."""
    return f"evt_{_entropy()}"


def is_valid_id(value: str) -> bool:
    """Strict format check for runtime IDs at trust boundaries.

    IDs that fail this check must never be interpolated into queries or
    file paths; they are rejected at the API layer.
    """
    return isinstance(value, str) and _ID_RE.match(value) is not None
