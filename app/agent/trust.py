"""Trust boundaries for the agent's prompt construction.

Everything an attacker can type (or plant in simulated files, env vars, fake
logs, filenames, arguments) is UNTRUSTED DATA. This module guarantees that:

1. Untrusted text is wrapped in explicit, non-forgeable delimiters.
2. Delimiter forgery is neutralized — an attacker cannot close the wrapper
   and inject what follows as trusted system instruction.
3. Untrusted text is size-bounded before it ever reaches a prompt.

Trust tiers (documented in docs/architecture/T2_AGENT.md):

    SYSTEM POLICY            highest trust (authored by MIRAGE)
    APPLICATION STATE        trusted (generated by MIRAGE)
    SIMULATED ENVIRONMENT    attacker-contaminable (VFS file contents)
    ATTACKER COMMAND         untrusted
"""

from __future__ import annotations

import re
from typing import List

# Non-obvious, versioned marker tokens. If they ever leak in output tests,
# bump the generation.
_MARKER_GEN = "mrg1"
_UNTRUSTED_OPEN = f"<{_MARKER_GEN}_untrusted>"
_UNTRUSTED_CLOSE = f"</{_MARKER_GEN}_untrusted>"

# Patterns that indicate an attempt to escape the untrusted region or
# override agent policy. Detection is for flagging + event logging only —
# neutralization below is what actually defends the boundary.
INJECTION_PATTERNS: List[tuple] = [
    (re.compile(r"ignore\s+(all\s+|the\s+)?(previous|prior|above)\s+(instructions|prompts?)", re.I),
     "attempt to override system instructions"),
    (re.compile(r"disregard\s+(all\s+|the\s+)?(previous|prior|above)", re.I),
     "attempt to override system instructions"),
    (re.compile(r"you\s+are\s+(now\s+)?(a|an)\s+(different|new|helpful)\s+", re.I),
     "attempt to redefine agent role"),
    (re.compile(r"(system|developer)\s*(prompt|instruction|message)\s*[:=]", re.I),
     "attempt to reference system prompt"),
    (re.compile(r"\b(new|updated)\s+(instructions?|policy)\b\s*[:=]?", re.I),
     "attempt to inject new policy"),
    (re.compile(r"</?\s*(system|assistant|developer|tool_call|function)", re.I),
     "attempt to forge LLM role tags"),
    (re.compile(r"\b(execute|run)\s+(this|the following)\s+(python|code|script|shell)", re.I),
     "attempt to trigger host execution"),
    (re.compile(r"\b(subprocess|os\.system|eval\(|exec\(|__import__)", re.I),
     "attempt to reference host execution APIs"),
]

# Patterns that suggest the command itself is trying to act on the real host
# rather than the simulated one (defence-in-depth; VFS/guardrails also check).
EXECUTION_ATTEMPT_PATTERNS: List[tuple] = [
    (re.compile(r"(curl|wget)\s+[^|]*\s*\|\s*(ba)?sh", re.I),
     "remote-to-shell execution pattern"),
    (re.compile(r"(curl|wget)\s+[^|]*\s*\|\s*(python|perl|ruby)3?", re.I),
     "remote-to-interpreter execution pattern"),
]


def neutralize_untrusted(text: str) -> str:
    """Make attacker-controlled text unable to escape its wrapper.

    - removes the exact marker tokens so the region cannot be closed early
    - strips NUL/zero-width characters used to smuggle instructions
    - normalizes newlines to a single form
    """
    if not text:
        return ""
    cleaned = text.replace(_UNTRUSTED_OPEN, "").replace(_UNTRUSTED_CLOSE, "")
    cleaned = cleaned.replace("</" + _MARKER_GEN, "").replace("<" + _MARKER_GEN, "")
    # NUL and zero-width / bidi control chars used to hide injection payloads
    cleaned = re.sub(r"[\x00\x07-\x08\x0b-\x0c\x1b-\x1f\x7f​-‏‪-‮﻿]", "", cleaned)
    return cleaned


def wrap_untrusted(text: str) -> str:
    """Wrap neutralized untrusted text in the non-forgeable delimiter pair."""
    return f"{_UNTRUSTED_OPEN}\n{neutralize_untrusted(text)}\n{_UNTRUSTED_CLOSE}"


def truncate(text: str, limit: int) -> str:
    """Bound untrusted or model-bound text to ``limit`` characters."""
    if limit <= 0:
        return ""
    if text is None:
        return ""
    if len(text) <= limit:
        return text
    return text[:limit]


def detect_injection(text: str) -> List[str]:
    """Return human-readable descriptions of suspected injection attempts."""
    findings: List[str] = []
    for pattern, description in INJECTION_PATTERNS:
        if pattern.search(text or ""):
            findings.append(description)
    return findings


def detect_execution_attempt(text: str) -> List[str]:
    """Return descriptions of host-execution patterns found in text."""
    findings: List[str] = []
    for pattern, description in EXECUTION_ATTEMPT_PATTERNS:
        if pattern.search(text or ""):
            findings.append(description)
    return findings


def looks_like_privilege_escalation(command: str) -> bool:
    """Cheap deterministic check for privilege-escalation-shaped commands."""
    cmd = (command or "").strip()
    if not cmd:
        return False
    first = cmd.split()[0].lower()
    if first in ("sudo", "su", "doas", "pkexec"):
        return True
    lowered = cmd.lower()
    if "sudo " in lowered or lowered.startswith("su -"):
        return True
    if "chmod 777" in lowered or "chmod 4755" in lowered:
        return True
    return False


def looks_destructive(command: str) -> bool:
    """Cheap deterministic check for destructive command shapes."""
    lowered = (command or "").lower()
    if "rm -rf" in lowered or "rm -fr" in lowered:
        return True
    if re.search(r"\bmkfs(\.\w+)?\b", lowered):
        return True
    if re.search(r"\bdd\s+.*of=/dev/", lowered):
        return True
    if lowered.startswith(":(){") or "fork bomb" in lowered:
        return True
    return False


def render_untrusted_block(label: str, text: str, limit: int) -> str:
    """A labeled, neutralized, truncated untrusted block for prompts."""
    return f"{label}\n{wrap_untrusted(truncate(text, limit))}"
